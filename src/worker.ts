export interface Env {
  ASSETS: Fetcher;
}

const USER_ID = "95942e40-7565-4a59-a5e7-8536ef17bfde";
const SUNO_FEED_URL = "https://suno.com/a/api/unified/feed";

interface SunoClip {
  id: string;
  title: string;
  status: string;
  is_public?: boolean;
  is_trashed?: boolean;
  is_hidden?: boolean;
  play_count?: number;
  upvote_count?: number;
  image_url?: string;
  image_large_url?: string;
  major_model_version?: string;
  model_name?: string;
  video_url?: string;
  display_tags?: string;
  created_at?: string;
  metadata?: {
    tags?: string;
    prompt?: string;
    duration?: number;
    negative_tags?: string;
    is_max_mode?: boolean;
    vox_render_mode?: string;
    make_instrumental?: boolean;
    control_sliders?: {
      style_weight?: number;
      weirdness_constraint?: number;
      aug_creativity?: number;
    };
  };
}

function detectLanguage(title: string, lyrics: string, tags: string): string {
  const deWords = /\b(und|der|die|das|ich|du|wir|nicht|nacht|feuer|tanz|schrei|leben|kein|alle|heute|immer|wieder|durch|auf|ansschlag|vollgas)\b/i;
  const esWords = /\b(el|la|los|las|de|en|y|que|por|para|con|noche|fuego|amor|corazón|olé|bailar|vamos|dale|hasta|amanecer|súbelo|turbolé|carambassa)\b/i;
  const sample = `${title} ${tags} ${lyrics.substring(0, 1000)}`.toLowerCase();

  const deCount = (sample.match(new RegExp(deWords, "gi")) || []).length;
  const esCount = (sample.match(new RegExp(esWords, "gi")) || []).length;

  if (deCount > esCount && deCount >= 2) return "DE";
  if (esCount >= 2) return "ES";
  return "EN";
}

function extractStructureCues(lyrics: string): string[] {
  const cues: string[] = [];
  const cueRegex = /\[([^\]]+)\]/g;
  let cm: RegExpExecArray | null;
  while ((cm = cueRegex.exec(lyrics)) !== null && cues.length < 8) {
    const rawCue = cm[1].trim();
    if (rawCue.length > 2 && rawCue.length < 70 && !cues.includes(rawCue)) {
      cues.push(rawCue);
    }
  }
  if (cues.length === 0) {
    cues.push("Full Song Structure", "Generated by ChatGPT", "Arranged for Suno V6");
  }
  return cues;
}

function formatClip(clip: SunoClip, index: number) {
  const meta = clip.metadata || {};
  const tags = meta.tags || clip.display_tags || "";
  const lyrics = meta.prompt || "";
  const title = clip.title || "Untitled";

  const bpmMatch = tags.match(/(\d{2,3})\s*(?:-|–|\/)?\s*(?:\d{2,3})?\s*BPM/i);
  let bpm = bpmMatch ? parseInt(bpmMatch[1], 10) : 128;
  if (bpm < 60 || bpm > 210) bpm = 128;

  const language = detectLanguage(title, lyrics, tags);
  const durSec = Math.round(meta.duration || 240);
  const durMin = Math.floor(durSec / 60);
  const durRem = durSec % 60;
  const duration = `${durMin}:${durRem < 10 ? "0" : ""}${durRem}`;

  const cues = extractStructureCues(lyrics);
  const sliders = meta.control_sliders || {};

  return {
    id: clip.id,
    number: String(index + 1).padStart(3, "0"),
    title: title,
    bpm: bpm,
    language: language,
    playCount: clip.play_count || 0,
    upvoteCount: clip.upvote_count || 0,
    durationSeconds: durSec,
    duration: duration,
    model: `Suno ${clip.major_model_version ? clip.major_model_version.toUpperCase() : "V6"} (${clip.model_name || "chirp-hawk"})`,
    displayTags: clip.display_tags || "",
    shortStyle: tags.length > 55 ? tags.substring(0, 55) + "..." : tags,
    stylePrompt: tags,
    negativeTags: meta.negative_tags || "",
    lyrics: lyrics,
    structureCues: cues,
    settings: {
      modelVersion: (clip.major_model_version || "v6").toUpperCase(),
      engineName: clip.model_name || "chirp-hawk",
      isMaxMode: Boolean(meta.is_max_mode ?? true),
      voxRenderMode: meta.vox_render_mode || "strict",
      styleWeight: sliders.style_weight ?? 0.88,
      weirdnessConstraint: sliders.weirdness_constraint ?? 0.28,
      augCreativity: sliders.aug_creativity ?? 0,
      makeInstrumental: Boolean(meta.make_instrumental),
      deliveryEncoding: "m4a-opus",
      createdAt: clip.created_at ? clip.created_at.split("T")[0] : "",
    },
    coverUrl: clip.image_large_url || clip.image_url || "",
    thumbUrl: clip.image_url || clip.image_large_url || "",
    audioUrl: `https://cdn1.suno.ai/${clip.id}.mp4`,
    videoUrl: clip.video_url || `https://cdn1.suno.ai/${clip.id}.mp4`,
    sunoUrl: `https://suno.com/song/${clip.id}`,
    embedUrl: `https://suno.com/embed/${clip.id}`,
  };
}

async function fetchLiveTracksFromSuno(): Promise<any[]> {
  let cursor: string | null = null;
  const allClips: SunoClip[] = [];

  while (true) {
    const body: Record<string, any> = {
      feed_id: "user_songs",
      page_size: 50,
      target_user_id: USER_ID,
    };
    if (cursor) body.cursor = cursor;

    const res = await fetch(SUNO_FEED_URL, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "User-Agent": "Mozilla/5.0 (compatible; v4nox-edge/1.0)",
      },
      body: JSON.stringify(body),
    });

    if (!res.ok) {
      break;
    }

    const json = (await res.json()) as any;
    const items = json?.feed?.items || [];
    if (items.length === 0) break;

    for (const item of items) {
      const clip = item.content_item;
      // Only include songs that are complete, explicitly public/published by the user, and not trashed or hidden
      if (
        clip &&
        clip.status === "complete" &&
        clip.is_public === true &&
        !clip.is_trashed &&
        !clip.is_hidden
      ) {
        allClips.push(clip);
      }
    }

    cursor = json?.feed?.next_cursor;
    if (!cursor) break;
  }

  return allClips.map((c, i) => formatClip(c, i));
}

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);

    // Health and artist metadata API endpoint on Cloudflare Edge
    if (url.pathname === "/api/artist") {
      return Response.json(
        {
          artist: "v4nox",
          creator: "Dominik Hahn (@dome_hahn)",
          sunoProfile: "https://suno.com/@dome_hahn",
          spotifyProfile: "https://open.spotify.com/intl-de/artist/3Qsyrq3U8VNdCQzaEav3mf",
          amazonMusicProfile: "https://www.amazon.com/music/player/artists/B0HQYFFZ9L/v4nox",
          domain: "v4nox.eu",
          engine: "Suno AI Audio Synthesis + Cloudflare Workers Edge",
          status: "online",
        },
        {
          headers: {
            "Cache-Control": "public, max-age=3600",
            "X-Content-Type-Options": "nosniff",
          },
        }
      );
    }

    // Dynamic live Suno tracks endpoint on Cloudflare Edge with Edge Cache
    if (url.pathname === "/api/tracks") {
      const forceRefresh = url.searchParams.has("refresh") || url.searchParams.has("force");
      const cache = caches.default;
      const cacheKey = new Request(url.origin + url.pathname, request);

      if (!forceRefresh) {
        const cachedResponse = await cache.match(cacheKey);
        if (cachedResponse) {
          return cachedResponse;
        }
      }

      try {
        const tracks = await fetchLiveTracksFromSuno();
        const responseData = {
          success: true,
          total: tracks.length,
          lastSynced: new Date().toISOString(),
          tracks,
        };

        const res = Response.json(responseData, {
          headers: {
            "Content-Type": "application/json; charset=utf-8",
            "Cache-Control": "public, s-maxage=600, max-age=300, stale-while-revalidate=86400",
            "X-Content-Type-Options": "nosniff",
            "Access-Control-Allow-Origin": "*",
          },
        });

        // Store in Cloudflare Edge cache in background
        ctx.waitUntil(cache.put(cacheKey, res.clone()));
        return res;
      } catch (err: any) {
        return Response.json(
          {
            success: false,
            error: err?.message || "Failed to fetch tracks from Suno",
          },
          {
            status: 502,
            headers: {
              "Cache-Control": "no-cache",
              "X-Content-Type-Options": "nosniff",
            },
          }
        );
      }
    }

    // Serve static assets with security headers
    const response = await env.ASSETS.fetch(request);
    const headers = new Headers(response.headers);
    headers.set("X-Content-Type-Options", "nosniff");
    headers.set("X-Frame-Options", "SAMEORIGIN");
    headers.set("Referrer-Policy", "strict-origin-when-cross-origin");

    return new Response(response.body, {
      status: response.status,
      statusText: response.statusText,
      headers,
    });
  },
} satisfies ExportedHandler<Env>;
